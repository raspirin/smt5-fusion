use crate::model::race::{Element, Race};

#[derive(Debug, Clone, Copy)]
pub(crate) struct FusionTable {
    rows: &'static [&'static [Option<Race>]],
}

impl FusionTable {
    const fn new(rows: &'static [&'static [Option<Race>]]) -> Self {
        Self { rows }
    }

    pub(crate) fn result(&self, left: Race, right: Race) -> Option<Race> {
        let left = left.fusion_index()?;
        let right = right.fusion_index()?;
        let (row, column) = if left >= right {
            (left, right)
        } else {
            (right, left)
        };

        self.rows.get(row)?.get(column).copied().flatten()
    }
}

